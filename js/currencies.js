window.obtenerMonedaPrecio3D = function obtenerMonedaPrecio3D(codigo) {
  return window.MonedasPrecio3D.find((moneda) => moneda.codigo === String(codigo || "").toUpperCase()) || null;
};

window.formatearMonedaPrecio3D = function formatearMonedaPrecio3D(valor, codigoMoneda = "CLP", locale) {
  const moneda = window.obtenerMonedaPrecio3D(codigoMoneda) || window.obtenerMonedaPrecio3D("CLP");
  const numero = Number(valor);

  return new Intl.NumberFormat(locale || moneda.locale, {
    style: "currency",
    currency: moneda.codigo,
    currencyDisplay: "symbol"
  }).format(Number.isFinite(numero) ? numero : 0);
};
