// Cambia solo los textos marcados, sin traducir toda la app todavia.
function cambiarIdioma(idioma) {
  const idiomaActivo = window.IdiomasPrecio3D[idioma] || window.IdiomasPrecio3D.es;

  document.documentElement.lang = idioma;

  document.querySelectorAll("[data-i18n]").forEach((elemento) => {
    const clave = elemento.dataset.i18n;
    const texto = idiomaActivo.textos[clave];

    if (texto) {
      elemento.textContent = texto;
    }
  });
}

window.cambiarIdioma = cambiarIdioma;
