// Cambia solo los textos marcados, sin traducir toda la app todavia.
function obtenerTextoI18n(clave, reemplazos = {}, idioma = document.documentElement.lang || "es") {
  const idiomaActivo = window.IdiomasPrecio3D[idioma] || window.IdiomasPrecio3D.es;
  const textoBase = idiomaActivo.textos[clave] || window.IdiomasPrecio3D.es.textos[clave] || "";
  return Object.entries(reemplazos).reduce(
    (texto, [llave, valor]) => texto.replaceAll(`{${llave}}`, valor),
    textoBase
  );
}

// Conserva una referencia solo a los nodos originales de index.html. Así se
// completan textos estáticos heredados sin tocar nombres ni datos renderizados
// posteriormente por los paneles dinámicos.
const nodosEstaticosInterfaz = typeof document === "undefined"
  ? []
  : Array.from(document.querySelectorAll("body *"));
const clavesTextoEstatico = new WeakMap();
const clavesAtributoEstatico = new WeakMap();

function traducirTextosEstaticosHeredados(idioma) {
  const textosBase = window.IdiomasPrecio3D.es.textos;
  const clavePorTexto = new Map(
    Object.entries(textosBase)
      .filter(([, texto]) => typeof texto === "string" && !texto.includes("{"))
      .map(([clave, texto]) => [texto.trim(), clave])
  );

  nodosEstaticosInterfaz.forEach((elemento) => {
    if (!elemento.isConnected || elemento.matches("script, style")) return;

    Array.from(elemento.childNodes)
      .filter((nodo) => nodo.nodeType === Node.TEXT_NODE && nodo.textContent.trim())
      .forEach((nodo) => {
        const contenido = nodo.textContent;
        const texto = contenido.trim();
        const clave = clavesTextoEstatico.get(nodo) || clavePorTexto.get(texto);
        if (!clave) return;
        clavesTextoEstatico.set(nodo, clave);
        nodo.textContent = contenido.replace(texto, obtenerTextoI18n(clave, {}, idioma));
      });

    ["title", "placeholder", "aria-label"].forEach((atributo) => {
      const valor = elemento.getAttribute(atributo)?.trim();
      const clavesElemento = clavesAtributoEstatico.get(elemento) || {};
      const clave = clavesElemento[atributo] || (valor ? clavePorTexto.get(valor) : "");
      if (clave) {
        clavesElemento[atributo] = clave;
        clavesAtributoEstatico.set(elemento, clavesElemento);
      }
      if (clave) elemento.setAttribute(atributo, obtenerTextoI18n(clave, {}, idioma));
    });

    if (elemento.matches(".info-btn[data-help]") && !elemento.dataset.i18nAriaLabel) {
      elemento.setAttribute("aria-label", obtenerTextoI18n("informacionCampo", {}, idioma));
    }
  });
}

function cambiarIdioma(idioma) {
  const idiomaActivo = window.IdiomasPrecio3D[idioma] || window.IdiomasPrecio3D.es;

  document.documentElement.lang = idioma;

  document.querySelectorAll("[data-i18n]").forEach((elemento) => {
    const clave = elemento.dataset.i18n;
    const texto = idiomaActivo.textos[clave] || window.IdiomasPrecio3D.es.textos[clave];

    if (texto) {
      elemento.textContent = texto;
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach((elemento) => {
    const texto = idiomaActivo.textos[elemento.dataset.i18nTitle] || window.IdiomasPrecio3D.es.textos[elemento.dataset.i18nTitle];
    if (texto) {
      elemento.title = texto;

      if (elemento.dataset.tooltip !== undefined) {
        elemento.dataset.tooltip = texto;
      }
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((elemento) => {
    const texto = idiomaActivo.textos[elemento.dataset.i18nPlaceholder] || window.IdiomasPrecio3D.es.textos[elemento.dataset.i18nPlaceholder];
    if (texto) elemento.placeholder = texto;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((elemento) => {
    const texto = idiomaActivo.textos[elemento.dataset.i18nAriaLabel] || window.IdiomasPrecio3D.es.textos[elemento.dataset.i18nAriaLabel];
    if (texto) elemento.setAttribute("aria-label", texto);
  });

  traducirTextosEstaticosHeredados(idioma);
  document.dispatchEvent(new CustomEvent("precio3d:idioma-actualizado", { detail: { idioma } }));
}

window.obtenerTextoI18n = obtenerTextoI18n;
window.cambiarIdioma = cambiarIdioma;

